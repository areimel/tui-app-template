/**
Generate a heading art module (ANSI Shadow font via figlet).

Run with `npx tsx scripts/generate-heading.ts [--text <TEXT>] [--out <file>]`. Defaults: text `APP.headingText`, out `source/shell/brand/heading-art.ts` (the menu heading; the init script regenerates it). Keep Awake's own art was made with `--text COFFEE --out source/apps/keep-awake/features/heading/heading-art.ts`. Importing this module has no side effects; the file is only written when the script is the entry point.
*/
import {mkdirSync, writeFileSync} from 'node:fs';
import {dirname, resolve} from 'node:path';
import process from 'node:process';
import {fileURLToPath, pathToFileURL} from 'node:url';
import figlet from 'figlet';
import ansiShadow from 'figlet/importable-fonts/ANSI Shadow.js';
import {APP} from '../source/app.config.js';

const FONT_NAME = 'ANSI Shadow';

const DEFAULT_OUTPUT_PATH = fileURLToPath(
	new URL('../source/shell/brand/heading-art.ts', import.meta.url),
);

/**
Render `text` with the ANSI Shadow font as an array of equal-width rows.

Trailing all-blank rows are dropped. Rows are padded to the widest row but their inner spacing is left untouched.
*/
export function renderHeading(text: string = APP.headingText): string[] {
	figlet.parseFont(FONT_NAME, ansiShadow);
	const rows = figlet
		.textSync(text, {font: FONT_NAME})
		.split('\n')
		.map(row => row.replace(/\r$/v, ''));

	while (rows.length > 0 && rows.at(-1)?.trim() === '') {
		rows.pop();
	}

	const width = Math.max(...rows.map(row => row.length));
	return rows.map(row => row.padEnd(width));
}

/**
Produce the TypeScript source of the generated module for the given rows.
*/
export function emitHeadingModule(
	lines: readonly string[],
	text: string = APP.headingText,
): string {
	for (const line of lines) {
		if (/['\\]/v.test(line)) {
			throw new Error(
				`Heading line contains a character that needs escaping: ${line}`,
			);
		}
	}

	if (/['\\]/v.test(text)) {
		throw new Error(`Heading text needs escaping: ${text}`);
	}

	const width = lines[0]?.length ?? 0;
	const body = lines.map(line => `\t'${line}',`).join('\n');

	return `// Generated by scripts/generate-heading.ts. Do not edit by hand.

export const HEADING_TEXT = '${text}';
export const HEADING_WIDTH = ${width};
export const HEADING_HEIGHT = ${lines.length};
export const HEADING_LINES: readonly string[] = [
${body}
];
`;
}

/**
Read the value following `flag` in `argv`, if any.
*/
function readFlag(argv: readonly string[], flag: string): string | undefined {
	const index = argv.indexOf(flag);
	return index === -1 ? undefined : argv[index + 1];
}

/**
Render `text` and write the module to `out`; returns the row count.
*/
export function writeHeadingFile(text: string, out: string): number {
	const lines = renderHeading(text);
	mkdirSync(dirname(out), {recursive: true});
	writeFileSync(out, emitHeadingModule(lines, text));
	return lines.length;
}

if (
	process.argv[1] !== undefined &&
	import.meta.url === pathToFileURL(process.argv[1]).href
) {
	const argv = process.argv.slice(2);
	const text = readFlag(argv, '--text') ?? APP.headingText;
	const flagOut = readFlag(argv, '--out');
	const out = flagOut === undefined ? DEFAULT_OUTPUT_PATH : resolve(flagOut);
	const rows = writeHeadingFile(text, out);
	console.log(`Wrote ${out} (${rows} rows)`);
}
